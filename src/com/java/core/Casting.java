package com.java.core;

public class Casting {
	public static void main(String[] args) {
		//Implicite casting
		int a = 23;
		double d = a;
		System.out.println("value of d is :" +d );
         
	 // explicite casting
		double b = 98.29;
		int z = (int) b;
		System.out.println("Value of z is : " +z);
	}

}
